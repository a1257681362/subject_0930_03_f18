-- museum-16 文物修复年度报表
--   设计要点：
--   1) 指标口径版本化（t_annual_caliber_version）：五项指标（立项数/完成数/
--      材料消耗/借展次数/异常事件）各自的归属时间字段、计入状态等口径随版本
--      固化为 JSON；发布新版本旧版本置 SUPERSEDED 只追加。报表核对恒按其
--      绑定的 caliber_version_id 执行——即使口径后续发布新版本，已出报表仍按
--      原版本完成核对。
--   2) 年度报表按批次归档（t_annual_report）：同一年度同一口径版本可多次
--      生成，每次一条不可变快照（GENERATED），编号带批次号；撤回只置
--      REVOKED（保留全部快照与凭证），重提另出新批次、新编号、新时间，
--      撤回链以 revoked_of_id 串联，编号/口径版本/时间三者都可辨。
--   3) 缺验收资料的完成项目只标记 PENDING_SUPPLEMENT（待补），不影响其余
--      指标；快照头/明细/待补项目行生成后不可变。
--   4) 异常事件只追加凭证（t_annual_report_anomaly），同一异常可多次追加，
--      永不覆盖已有凭证；报表异常事件总数同时落头表便于裁剪导出。
--   5) Quartz 生成任务全程写任务日志（t_annual_report_job_log，只追加）：
--      每轮（含手动触发）一条 RUNNING -> SUCCESS/FAILED 日志；失败写 FAILED
