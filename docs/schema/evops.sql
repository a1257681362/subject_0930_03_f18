-- museum-10 文物借阅审批
--   设计要点：
--   1) 按保护等级配置借阅策略（t_borrow_grade_policy）：每个等级一行，
--      配置可借阅场景、最高借阅天数、有序审批角色；一级（高风险）必须
--      追加馆长签名（director_sign_required=1）。策略只维护单行当前值，
--      申请提交时把场景/时长/审批角色/馆长要求固化进申请与借阅快照，
--      之后策略调整不影响在途审批（与规则版本快照同一口径）。
--   2) 借阅申请（t_borrow_application）提交时校验：文物在档、无未闭环
--      借阅/借出/借展协议、不在当前展陈计划（t_hall_relic ON_DISPLAY）、
--      不存在未终结修复项目；场景与时长不得超出该等级策略。
--   3) 审批按固化角色顺序逐人签署（t_borrow_approval_record）：
--      uk(extension_id, step_no) 同时约束初审链与延期重审链（extension_id
--      为空表示原申请审批，H2 唯一索引允许多个 NULL）；任一驳回即终止；
--      高风险链最后一步必须为馆长本人签名。全部通过后 APPROVED 并生成
--      不可变借阅快照（t_borrow_snapshot）。
--   4) 批准出库（APPROVED -> BORROWED）向 t_relic_loan 写 LENT 贯通记录，
--      继续复用 museum-1 跨业务占用校验；归还只闭环不抹除。
--   5) 归还延期（t_borrow_extension）必须重新走完整审批链（高风险仍须
--      馆长签名）；延期驳回不改变原应还时间；审批中归还则延期单自动驳回。
--   6) 保险资料按馆区隔离：申请/快照/借阅补偿中的保险金额只对文物所属
--      馆区（t_relic.campus_code）的查看人完整返回，其他馆区审批人看到
--      脱敏视图（金额置空、viewable=0），不返回任何保险数字。
--   7) 修复验收"附条件通过"（部分成功）即开立保护等级补偿
--      （t_repair_grade_compensation，一项目一条）：登记等级前/后；若文物
--      存在在借/待出库借阅或最近一次借阅，则成对开立借阅补偿
--      （t_borrow_compensation，RECALL 提前收回 / SUPPLEMENT_CONFIRM 差异
--      确认），两条补偿互相持有对方 id，借阅补偿闭环后等级补偿方可确认，
--      确保保护等级调整与借阅侧处置一一对应、联动闭环。
-- ========================================================================

