-- ========================================================================
-- museum-7 文物库房库位与密集架预约
--   设计要点：
--   1) 库位按温区（恒温/冷藏/常温）、防火等级（F1/F2/F3）与承重维护：
--      库区 t_storage_area、密集架 t_storage_rack、格位 t_storage_cell 三级，
--      停用只置状态，历史移动与台账永不删改。
--   2) 搬入前必须预约目标格位（t_storage_reservation）：以 hold_key 稀疏唯一
--      约束保证同一格位同时只有一个在途（RESERVED/MOVING）预约；预约超时由
--      定时扫描自动释放，但 WHERE 只命中 RESERVED——已开工（MOVING）格位
--      永不释放。
--   3) 互斥设备同一时段只允许一个操作：以密集架（t_storage_rack）为互斥单位，
--      同一架体上时间窗重叠的在途预约/移动一律拒绝，架体行 SELECT ... FOR
--      UPDATE 串行化并发。
--   4) 移动单（t_storage_move_order）一预约一条，固化原位/目的位/箱号/操作
--      人员快照；完成移动在 t_storage_stock 原子清原格、立目的格。
--   5) 请求流水号 request_no 唯一：修复侧补传/补录/重试复用同一 requestNo，
--      预约只形成一条可用结果，绝不产生第二条。
--   6) 库存查询按馆员权限隐藏敏感位置：WAREHOUSE_KEEPER 见全部，CURATOR
--      保留敏感格位行但精确位置脱敏，VIEWER 直接过滤敏感格位。
--   7) 库房台账 t_storage_ledger 只追加：建档/预约/取消/超时释放/开工/完成
--      全部留痕。
-- ========================================================================

-- ------------------------------------------------------------------------
-- 34. 库区：按温区、防火等级、承重维护
--     temp_zone:  CONST_TEMP 恒温 / COLD 冷藏 / ORDINARY 常温
--     fire_rating: F1 / F2 / F3（F1 防火等级最高）
--     status: ACTIVE 在用 / CLOSED 已关闭（关闭不删历史）
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_storage_area (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area_no          VARCHAR(40)  NOT NULL,
    name             VARCHAR(128) NOT NULL,
    temp_zone        VARCHAR(16)  NOT NULL,
    fire_rating      VARCHAR(8)   NOT NULL,
    load_capacity_kg DECIMAL(12,2) NOT NULL,
    location         VARCHAR(255),
    manager          VARCHAR(64),
    status           VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    create_by        BIGINT,
    create_time      TIMESTAMP,
    update_by        BIGINT,
    update_time      TIMESTAMP,
    CONSTRAINT uk_storage_area_no UNIQUE (area_no),
    CONSTRAINT ck_storage_area_zone CHECK (temp_zone IN ('CONST_TEMP', 'COLD', 'ORDINARY')),
    CONSTRAINT ck_storage_area_fire CHECK (fire_rating IN ('F1', 'F2', 'F3')),
    CONSTRAINT ck_storage_area_status CHECK (status IN ('ACTIVE', 'CLOSED')),
    CONSTRAINT ck_storage_area_load CHECK (load_capacity_kg >= 0)
);

-- ------------------------------------------------------------------------
-- 35. 密集架（互斥设备）：同一架体同一时段只允许一个移动操作
--     status: ACTIVE 在用 / CLOSED 已停用
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_storage_rack (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rack_no          VARCHAR(40)  NOT NULL,
    area_id          BIGINT NOT NULL,
    equipment_no     VARCHAR(40)  NOT NULL,
    name             VARCHAR(128),
    aisle            VARCHAR(64),
    status           VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    create_by        BIGINT,
    create_time      TIMESTAMP,
    update_by        BIGINT,
    update_time      TIMESTAMP,
    CONSTRAINT uk_storage_rack_no UNIQUE (rack_no),
    CONSTRAINT uk_storage_rack_equip UNIQUE (equipment_no),
    CONSTRAINT ck_storage_rack_status CHECK (status IN ('ACTIVE', 'CLOSED'))
);
CREATE INDEX IF NOT EXISTS idx_storage_rack_area ON t_storage_rack (area_id);

-- ------------------------------------------------------------------------
-- 36. 格位：密集架上的具体存放格口，承继库区温区/防火等级并可细化承重上限。
--     sensitive=1 为敏感位置，库存查询对低权限馆员脱敏/过滤。
--     status: ACTIVE 可用 / DISABLED 已停用（停用不影响在途与历史）
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_storage_cell (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cell_no          VARCHAR(40)  NOT NULL,
    area_id          BIGINT NOT NULL,
    rack_id          BIGINT NOT NULL,
    shelf_no         INT,
    col_no           INT,
    temp_zone        VARCHAR(16)  NOT NULL,
    fire_rating      VARCHAR(8)   NOT NULL,
    load_limit_kg    DECIMAL(12,2) NOT NULL,
    sensitive        INT NOT NULL DEFAULT 0,
    status           VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    create_by        BIGINT,
    create_time      TIMESTAMP,
    update_by        BIGINT,
    update_time      TIMESTAMP,
    CONSTRAINT uk_storage_cell_no UNIQUE (cell_no),
    CONSTRAINT ck_storage_cell_zone CHECK (temp_zone IN ('CONST_TEMP', 'COLD', 'ORDINARY')),
    CONSTRAINT ck_storage_cell_fire CHECK (fire_rating IN ('F1', 'F2', 'F3')),
    CONSTRAINT ck_storage_cell_status CHECK (status IN ('ACTIVE', 'DISABLED')),
    CONSTRAINT ck_storage_cell_sensitive CHECK (sensitive IN (0, 1)),
    CONSTRAINT ck_storage_cell_load CHECK (load_limit_kg >= 0)
);
CREATE INDEX IF NOT EXISTS idx_storage_cell_rack ON t_storage_cell (rack_id);
CREATE INDEX IF NOT EXISTS idx_storage_cell_area ON t_storage_cell (area_id);

-- ------------------------------------------------------------------------
-- 37. 库位预约（兼移动主单）：搬入前必须预约目标格位。
--     status: RESERVED 已预约 / MOVING 已开工 / COMPLETED 已完成
--             / CANCELLED 已取消 / EXPIRED 超时释放
--     request_no 请求流水号（修复侧补传/补录/重试复用），uk 保证只形成一条结果。
--     hold_key 稀疏唯一：在途（RESERVED/MOVING）时 hold_key=目标格位 id，
--             终态置 NULL；同一格位同时只有一个在途预约（H2 唯一索引允许多个 NULL）。
--     超时扫描只 WHERE status='RESERVED' AND expire_at<now：MOVING 永不释放。
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_storage_reservation (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_no       VARCHAR(64)  NOT NULL,
    reservation_no   VARCHAR(40)  NOT NULL,
    area_id          BIGINT NOT NULL,
    rack_id          BIGINT NOT NULL,
    target_cell_id   BIGINT NOT NULL,
    origin_cell_id   BIGINT,
    relic_id         BIGINT,
    box_no           VARCHAR(64)  NOT NULL,
    weight_kg        DECIMAL(12,2),
    plan_start_time  TIMESTAMP NOT NULL,
    plan_end_time    TIMESTAMP NOT NULL,
    reserved_by      VARCHAR(64) NOT NULL,
    expire_at        TIMESTAMP NOT NULL,
    operator         VARCHAR(64),
    started_at       TIMESTAMP,
    finished_at      TIMESTAMP,
    hold_key         BIGINT,
    status           VARCHAR(16)  NOT NULL DEFAULT 'RESERVED',
    cancel_reason    VARCHAR(255),
    create_by        BIGINT,
    create_time      TIMESTAMP,
    update_by        BIGINT,
    update_time      TIMESTAMP,
    CONSTRAINT uk_storage_request_no UNIQUE (request_no),
    CONSTRAINT uk_storage_reservation_no UNIQUE (reservation_no),
    CONSTRAINT uk_storage_cell_hold UNIQUE (hold_key),
    CONSTRAINT ck_storage_res_status CHECK (status IN
        ('RESERVED', 'MOVING', 'COMPLETED', 'CANCELLED', 'EXPIRED')),
    CONSTRAINT ck_storage_res_window CHECK (plan_start_time < plan_end_time)
);
CREATE INDEX IF NOT EXISTS idx_storage_res_rack_time ON t_storage_reservation (rack_id, plan_start_time);
CREATE INDEX IF NOT EXISTS idx_storage_res_status_expire ON t_storage_reservation (status, expire_at);
CREATE INDEX IF NOT EXISTS idx_storage_res_box ON t_storage_reservation (box_no);

CREATE SEQUENCE IF NOT EXISTS seq_storage_reservation_no START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE IF NOT EXISTS seq_storage_move_order_no START WITH 1 INCREMENT BY 1;

-- ------------------------------------------------------------------------
