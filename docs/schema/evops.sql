    handle_remark    VARCHAR(500),
    handled_at       TIMESTAMP,
    review_by        VARCHAR(64),
    review_remark    VARCHAR(500),
    reviewed_at      TIMESTAMP,
    close_remark     VARCHAR(500),
    closed_at        TIMESTAMP,
    status           VARCHAR(16) NOT NULL DEFAULT 'OPEN',
    create_by        BIGINT,
    create_time      TIMESTAMP,
    update_by        BIGINT,
    update_time      TIMESTAMP,
    CONSTRAINT uk_env_event_no UNIQUE (event_no),
    CONSTRAINT uk_env_event_merge UNIQUE (merge_key),
    CONSTRAINT ck_env_event_metric CHECK (metric IN ('TEMP', 'HUMIDITY', 'LUX')),
